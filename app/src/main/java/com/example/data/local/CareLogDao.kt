package com.example.data.local

import androidx.room.Dao
import androidx.room.Delete
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.Query
import com.example.data.model.CareLog
import kotlinx.coroutines.flow.Flow

/**
 * CareLogDao manages the agronomic telemetry and maintenance event ledger in Room.
 *
 * DESIGN DECISIONS & TECHNICAL LOGIC:
 * 1. Chronological Sorting Strategies:
 *    - Feed queries use `ORDER BY timestamp DESC` so the most recent irrigation, nutrient mixing,
 *      pruning, or IPM spray appears immediately at the top of the event timeline.
 *    - Range-based heatmap queries use `ORDER BY timestamp ASC` so the HeatmapCalculator can iterate
 *      sequentially forward through 16-week or 52-week time buckets without index backtracking.
 * 2. Plant Isolation & Foreign Key Coupling:
 *    - `WHERE plantId = :plantId` scopes maintenance history strictly to the selected cultivar,
 *      preventing cross-contamination of telemetry (e.g. different EC/pH levels across coco vs soil).
 * 3. Latest-Log Optimization:
 *    - `getLatestLogForPlant(plantId)` executes `ORDER BY timestamp DESC LIMIT 1`. This provides
 *      an O(1) index-backed probe to determine how many hours have elapsed since the last watering,
 *      allowing the app to compute dry-back intervals without materializing hundreds of past records.
 */
@Dao
interface CareLogDao {
    /**
     * Continuous reactive stream of all care logs across all cultivars, sorted newest first.
     * Feeds the global Activity Ledger and timeline feed in HomeScreen.
     */
    @Query("SELECT * FROM care_logs ORDER BY timestamp DESC")
    fun getAllCareLogs(): Flow<List<CareLog>>

    /**
     * One-shot snapshot of all care logs for offline database export and JSON/CSV backups.
     */
    @Query("SELECT * FROM care_logs ORDER BY timestamp DESC")
    suspend fun getAllCareLogsOnce(): List<CareLog>

    /**
     * Continuous reactive stream of care logs scoped to a single cultivar.
     * Backs the detail timeline and telemetry charts for the active plant.
     */
    @Query("SELECT * FROM care_logs WHERE plantId = :plantId ORDER BY timestamp DESC")
    fun getLogsForPlant(plantId: Long): Flow<List<CareLog>>

    /**
     * One-shot fetch of logs for a specific cultivar. Used during per-plant data export.
     */
    @Query("SELECT * FROM care_logs WHERE plantId = :plantId ORDER BY timestamp DESC")
    suspend fun getLogsForPlantOnce(plantId: Long): List<CareLog>

    /**
     * Fetches care events within an inclusive Unix epoch millisecond window, sorted chronologically ascending.
     * Designed specifically for [HeatmapCalculator] to populate contribution grids and calculate care streaks.
     */
    @Query("SELECT * FROM care_logs WHERE timestamp >= :startTimestamp AND timestamp <= :endTimestamp ORDER BY timestamp ASC")
    fun getLogsBetween(startTimestamp: Long, endTimestamp: Long): Flow<List<CareLog>>

    /**
     * Records a new agronomic maintenance entry (watering, nutrients, training, defoliation).
     * Returns the autogenerated primary key row ID.
     */
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertLog(log: CareLog): Long

    /**
     * Bulk-inserts care logs during seed data initialization or database restoration.
     * Executes in a single transactional SQLite statement.
     */
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertLogs(logs: List<CareLog>)

    /**
     * Removes an incorrect or obsolete care log entry.
     */
    @Delete
    suspend fun deleteLog(log: CareLog)

    /**
     * Retrieves the single most recent log for a cultivar.
     * Crucial for calculating elapsed dry-back hours to alert growers when watering is due.
     */
    @Query("SELECT * FROM care_logs WHERE plantId = :plantId ORDER BY timestamp DESC LIMIT 1")
    fun getLatestLogForPlant(plantId: Long): Flow<CareLog?>

    /**
     * Deletes all care logs from SQLite; used during database resets or unit tests.
     */
    @Query("DELETE FROM care_logs")
    suspend fun deleteAllCareLogs()
}

