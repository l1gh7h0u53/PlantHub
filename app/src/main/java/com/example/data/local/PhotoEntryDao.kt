package com.example.data.local

import androidx.room.Dao
import androidx.room.Delete
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.Query
import androidx.room.Update
import com.example.data.model.PhotoEntry
import kotlinx.coroutines.flow.Flow

/**
 * PhotoEntryDao manages the visual milestone gallery and canopy height progression in Room.
 *
 * DESIGN DECISIONS & TECHNICAL LOGIC:
 * 1. Progression Sorting (ORDER BY timestamp ASC for individual plants):
 *    - In contrast to general event feeds, [getPhotosForPlant] sorts chronologically ASCENDING.
 *      This allows PhotoVaultScreen to render a left-to-right or top-to-bottom developmental time-lapse
 *      (e.g. Day 1 -> Day 7 -> Day 14) and enables [CanopyGrowthAnalytics] to compute positive height
 *      deltas between consecutive developmental milestones.
 * 2. SQLite CursorWindow Protection:
 *    - The database stores URI strings pointing to private app sandbox storage (`context.filesDir/milestone_photos`)
 *      rather than raw binary image BLOBs. This ensures queries never breach SQLite's strict 2MB CursorWindow limit,
 *      allowing hundreds of milestone records to load instantly without out-of-memory exceptions.
 * 3. Atomic Updates & Deletions:
 *    - [updatePhoto] and [deletePhoto] allow growers to revise canopy height measurements (cm) or
 *      agronomic observation notes after capture without disrupting photo file persistence.
 */
@Dao
interface PhotoEntryDao {
    /**
     * Continuous reactive stream of all photo milestone records across all cultivars, sorted newest first.
     * Backs the global Photo Vault overview grid.
     */
    @Query("SELECT * FROM photo_entries ORDER BY timestamp DESC")
    fun getAllPhotos(): Flow<List<PhotoEntry>>

    /**
     * One-shot fetch of all photo entries for database serialization in [PlantBackupManager].
     */
    @Query("SELECT * FROM photo_entries ORDER BY timestamp DESC")
    suspend fun getAllPhotosOnce(): List<PhotoEntry>

    /**
     * Chronological progression stream of photos for a specific cultivar, sorted oldest to newest.
     * Drives the plant's visual growth journey and weekly milestone cards.
     */
    @Query("SELECT * FROM photo_entries WHERE plantId = :plantId ORDER BY timestamp ASC")
    fun getPhotosForPlant(plantId: Long): Flow<List<PhotoEntry>>

    /**
     * One-shot chronological fetch of a cultivar's photos for export or delta computation.
     */
    @Query("SELECT * FROM photo_entries WHERE plantId = :plantId ORDER BY timestamp ASC")
    suspend fun getPhotosForPlantOnce(plantId: Long): List<PhotoEntry>

    /**
     * Inserts a new milestone photo record, returning the autogenerated ID.
     */
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertPhoto(photo: PhotoEntry): Long

    /**
     * Updates milestone metadata, canopy height measurements, or phenological notes.
     */
    @Update
    suspend fun updatePhoto(photo: PhotoEntry)

    /**
     * Deletes a milestone record from the database.
     */
    @Delete
    suspend fun deletePhoto(photo: PhotoEntry)

    /**
     * Clears all photo records; used during database resets.
     */
    @Query("DELETE FROM photo_entries")
    suspend fun deleteAllPhotos()
}

